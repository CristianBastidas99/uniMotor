package co.edu.uniquindio.unimotor.entidades;

/**
 * Tipo de combustible con el que funciona un vehículo.
 */
public enum TipoCombustible {
	/**
	 * Gasolina.
	 */
	GASOLINA,
	/**
	 * Bioetanol.
	 */
	BIOETANOL,
	/**
	 * Diésel (se conserva la grafía del nombre de la constante).
	 */
	DISEL,
	/**
	 * Biodiésel.
	 */
	BIODISEL,
	/**
	 * Gas natural.
	 */
	GASNATURAL,
	/**
	 * Híbrido (combustión y eléctrico).
	 */
	HIBRIDO,
	/**
	 * Eléctrico.
	 */
	ELECTRICO,
	/**
	 * Otro combustible no listado.
	 */
	OTRO
}
